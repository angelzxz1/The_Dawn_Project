// The Tremor's parity fixture for its Rust port
// (crates/dawn-engine/src/effects/tremor.rs): the cases, rendered with the
// worklet's own kernel (tremorModel.ts) the way the worklet runs it
// (tremor.ts) - a render quantum at a time, on the mono mix of the input
// (the node's one input channel takes stereo down-mixed, 0.5 * (L + R)) -
// as a generated Rust file and the rendered samples.
// tremorParity.test.ts checks the stored fixture still matches; the Rust
// side's tests/tremor_parity.rs compares the port against it. See
// src/test/kernelParity.ts.

import { TREMOR_SOURCE, tremorSettingsFromParams, type TremorSettings } from "./tremorModel";
import { FixtureData, PARITY_BLOCK, PARITY_FRAMES, PARITY_SAMPLE_RATE, PARITY_STRIDE, fnv1a, paritySignal, rustF64, rustHex, type ParitySignal } from "../../test/kernelParity";

interface Kernel {
  set(s: TremorSettings): void;
  process(input: Float32Array | null, output: Float32Array, n: number): void;
}

const Tremor = new Function(`${TREMOR_SOURCE}; return TremorKernel;`)() as new (sr: number) => Kernel;

export interface TremorParityCase {
  name: string;
  params: Record<string, number>;
  /** New parameters (over the case's) from this frame on - a block start. */
  change?: { at: number; params: Record<string, number> };
}

export const TREMOR_PARITY_CASES: TremorParityCase[] = [
  { name: "tube-defaults", params: {} },
  { name: "tube-deep-and-air", params: { gain: 7, ultraLo: 1, ultraHi: 1, comp: 6 } },
  { name: "tube-tight-no-comp", params: { gain: 2, blend: 3, ultraLo: 2, comp: 0, midFreq: 3, mid: 8 } },
  { name: "grind-raw-boost", params: { voice: 1, gain: 8, grunt: 0, attack: 2, blend: 5 } },
  { name: "grind-fat-cut", params: { voice: 1, gain: 10, grunt: 2, attack: 0, bass: 7, treble: 3 } },
  { name: "split-defaults", params: { voice: 2 } },
  { name: "split-moved", params: { voice: 2, gain: 9, lowSplit: 90, highSplit: 4500, midLevel: 6, highLevel: -18, comp: 10 } },
  { name: "eq-extremes", params: { voice: 1, bass: 0, mid: 10, treble: 10, midFreq: 0, output: -6 } },
  { name: "voice-switched", params: { gain: 6 }, change: { at: 50 * PARITY_BLOCK, params: { voice: 2, gain: 8, blend: 4 } } },
];

const changeParams = (c: TremorParityCase) => (c.change ? { ...c.params, ...c.change.params } : null);

function renderCase(c: TremorParityCase, sig: ParitySignal) {
  const k = new Tremor(PARITY_SAMPLE_RATE);
  k.set(tremorSettingsFromParams(c.params));
  const changed = changeParams(c);
  // The node's one input channel: the stereo input down-mixed.
  const mono = new Float32Array(PARITY_FRAMES);
  for (let i = 0; i < PARITY_FRAMES; i++) mono[i] = 0.5 * (sig.inL[i] + sig.inR[i]);
  const out = new Float32Array(PARITY_FRAMES);
  for (let start = 0; start < PARITY_FRAMES; start += PARITY_BLOCK) {
    if (c.change && changed && start === c.change.at) k.set(tremorSettingsFromParams(changed));
    const n = Math.min(PARITY_BLOCK, PARITY_FRAMES - start);
    k.process(mono.subarray(start, start + n), out.subarray(start, start + n), n);
  }
  return out;
}

const rustParams = (p: Record<string, number>) => `&[${Object.entries(p).map(([k, v]) => `("${k}", ${rustF64(v)})`).join(", ")}]`;

function rustCase(c: TremorParityCase): string {
  const changed = changeParams(c);
  return [
    "    Case {",
    `        name: "${c.name}",`,
    `        params: ${rustParams(c.params)},`,
    `        change: ${c.change && changed ? `Some((${c.change.at}, ${rustParams(changed)}))` : "None"},`,
    "    },",
  ].join("\n");
}

/** The fixture as it should be now: the Rust file's text, and the data
 * (per case: the kept samples of the one output). */
export function renderTremorParity(): { rust: string; data: FixtureData } {
  const sig = paritySignal();
  const data = new FixtureData();
  for (const c of TREMOR_PARITY_CASES) data.f32(renderCase(c, sig).filter((_, i) => i % PARITY_STRIDE === 0));
  const rust = [
    "// @generated by src/effects/tremor/tremorParity.test.ts from the JavaScript",
    "// kernel (tremorModel.ts). Don't edit it: to remake it, run",
    "// UPDATE_ENGINE_FIXTURES=1 npx vitest run --project unit tremorParity",
    "",
    `const SAMPLE_RATE: f64 = ${rustF64(PARITY_SAMPLE_RATE)};`,
    `const FRAMES: usize = ${PARITY_FRAMES};`,
    `const BLOCK: usize = ${PARITY_BLOCK};`,
    `const STRIDE: usize = ${PARITY_STRIDE};`,
    `const SIGNAL_HASH: u32 = ${rustHex(fnv1a([sig.inL, sig.inR, sig.keyL, sig.keyR]))};`,
    "",
    "const CASES: &[Case] = &[",
    ...TREMOR_PARITY_CASES.map(rustCase),
    "];",
    "",
  ].join("\n");
  return { rust, data };
}
